// Writes supabase/seed.sql from the validated files in data/. Rules keep the
// status recorded in their file, so only rules a person verified are served.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import type { RuleDoc } from "@permit-check/core";
import { DataError, PROJECTS, ROOT, loadJurisdictions, loadRules, type LoadedJurisdiction } from "./load-data.ts";

const lit = (v: string | null | undefined) => (v == null ? "null" : `'${v.replaceAll("'", "''")}'`);
const arr = (v: readonly string[]) => `array[${v.map(lit).join(", ")}]::text[]`;
const json = (v: unknown) => `${lit(JSON.stringify(v))}::jsonb`;
const idOf = (slug: string) => `(select id from jurisdictions where slug = ${lit(slug)})`;

function jurisdictionSql(j: LoadedJurisdiction): string {
  return `insert into jurisdictions (slug, name, kind, state_code, geoid, parent_id, aliases, building_dept_url, permit_portal_url, phone, adu_page_url, parcel_lookup_url, fee_schedule_url, contact_source_url, contacts_retrieved_at) values (${[
    lit(j.slug), lit(j.name), lit(j.kind), lit(j.state_code), lit(j.geoid),
    j.parent_slug ? idOf(j.parent_slug) : "null",
    arr(j.aliases), lit(j.building_dept_url), lit(j.permit_portal_url), lit(j.phone), lit(j.adu_page_url),
    lit(j.parcel_lookup_url), lit(j.fee_schedule_url), lit(j.contact_source_url), lit(j.contacts_retrieved_at),
  ].join(", ")});`;
}

function ruleSql(r: RuleDoc): string {
  const own = r.mode === "own" ? r : null;
  const cols = {
    jurisdiction_id: idOf(r.jurisdiction),
    project_type_id: `(select id from project_types where slug = ${lit(r.project)})`,
    mode: lit(r.mode),
    summary: lit(own?.summary),
    outcomes: own ? json(own.outcomes) : "null",
    default_verdict: lit(own?.default_verdict),
    default_explanation: lit(own?.default_explanation),
    default_citations: own ? arr(own.default_citations) : "null",
    permit_types: arr(own?.permit_types ?? []),
    fee_note: lit(own?.fee_note),
    docs_required: arr(own?.docs_required ?? []),
    inspections: arr(own?.inspections ?? []),
    notes: json(own?.notes ?? []),
    citations: json(r.citations),
    retrieved_at: lit(r.retrieved_at),
    status: lit(r.status),
    verified_by: lit(r.verified_by),
    verified_at: lit(r.verified_at),
    research_notes: lit(r.research_notes),
  };
  return `insert into rules (${Object.keys(cols).join(", ")}) values (${Object.values(cols).join(", ")});`;
}

try {
  const jurisdictions = loadJurisdictions();
  const rules = loadRules(jurisdictions);
  // Parents first so parent_id subqueries resolve.
  const ordered = [...jurisdictions].sort((a, b) => Number(a.parent_slug !== null) - Number(b.parent_slug !== null));
  const sql = [
    "-- Generated by scripts/build-seed-sql.ts from data/. Do not edit by hand.",
    "begin;",
    ...ordered.map(jurisdictionSql),
    ...jurisdictions.flatMap((j) =>
      j.county_slugs.map((c) => `insert into jurisdiction_counties (place_id, county_id) values (${idOf(j.slug)}, ${idOf(c)});`),
    ),
    ...PROJECTS.map((p, i) => `insert into project_types (slug, display_name, params, sort_order) values (${lit(p.slug)}, ${lit(p.display_name)}, ${json(p.params)}, ${i});`),
    ...rules.map(ruleSql),
    "commit;",
    "",
  ].join("\n");
  const out = join(ROOT, "supabase", "seed.sql");
  writeFileSync(out, sql);
  console.log(`wrote ${out}: ${jurisdictions.length} jurisdictions, ${PROJECTS.length} projects, ${rules.length} rules`);
} catch (err) {
  if (!(err instanceof DataError)) throw err;
  console.error(err.message);
  process.exit(1);
}
